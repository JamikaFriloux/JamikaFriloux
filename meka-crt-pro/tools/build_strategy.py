#!/usr/bin/env python3
"""Generate 'MEKA CRT PRO — Strategy.pine' from the indicator source.

The indicator is the single source of truth for the CRT engine. This script:
  1. swaps the indicator() declaration for a strategy() declaration,
  2. removes the alertcondition() block (not supported in strategies),
  3. appends tools/strategy_layer.pine at the #STRATEGY_HOOK marker.

Run from the meka-crt-pro folder:  python3 tools/build_strategy.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "MEKA CRT PRO — Indicator.pine"
OUT = ROOT / "MEKA CRT PRO — Strategy.pine"
LAYER = ROOT / "tools" / "strategy_layer.pine"

STRATEGY_HEADER = (
    'strategy("MEKA CRT PRO — Strategy", shorttitle = "MEKA CRT PRO S", overlay = true, '
    "initial_capital = 100000, currency = currency.USD, "
    "default_qty_type = strategy.fixed, default_qty_value = 2, pyramiding = 0, "
    "commission_type = strategy.commission.cash_per_contract, commission_value = 1.5, "
    "slippage = 2, margin_long = 5, margin_short = 5, "
    "process_orders_on_close = false, calc_on_every_tick = false, "
    "max_lines_count = 500, max_labels_count = 500, max_boxes_count = 300)"
)


def main() -> int:
    src = SRC.read_text(encoding="utf-8")
    header = re.compile(r"// #HEADER_BEGIN\n.*?\n// #HEADER_END", re.S)
    alerts = re.compile(r"// #ALERTCONDITIONS_BEGIN\n.*?// #ALERTCONDITIONS_END\n", re.S)
    for pat, name in ((header, "header"), (alerts, "alertconditions")):
        if len(pat.findall(src)) != 1:
            print(f"marker block '{name}' not found exactly once", file=sys.stderr)
            return 1
    if src.count("// #STRATEGY_HOOK") != 1:
        print("#STRATEGY_HOOK not found exactly once", file=sys.stderr)
        return 1

    out = header.sub("// #HEADER_BEGIN\n" + STRATEGY_HEADER + "\n// #HEADER_END", src)
    out = alerts.sub("// (alertcondition() block removed in the strategy build — alert() calls still work)\n", out)
    out = out.replace("// #STRATEGY_HOOK", LAYER.read_text(encoding="utf-8").rstrip() + "\n")
    out = out.replace(
        "//  MEKA CRT PRO — Candle Range Theory trading assistant (Pine Script v6)",
        "//  MEKA CRT PRO — STRATEGY BUILD (generated by tools/build_strategy.py — do not edit by hand)",
        1,
    )
    OUT.write_text(out, encoding="utf-8")
    print(f"wrote {OUT.name} ({len(out.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
